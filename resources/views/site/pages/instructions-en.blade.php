<h2>Before you pay</h2>
<ul>
<li>Do not send any money before you receive and accept our quote.</li>
<li>Pay only into the receiving account sent from our official number <span class="num">{{ config('alraed.whatsapp_display') }}</span>.</li>
<li>Receiving accounts change from time to time; every change is posted on the announcements page. If in doubt, ask before paying.</li>
</ul>
<h2>After you pay</h2>
<ul>
<li>Send us the receipt and transaction ID (TXID or bank reference) with your request reference.</li>
<li>A receipt photo alone is not enough: we approve a transfer only after confirming the funds actually reached our account.</li>
<li>Each receipt has one transaction ID; the same receipt or ID cannot be used for two requests.</li>
</ul>
<h2>On delivery</h2>
<ul>
<li>We deliver by the method and rate you accepted, and keep proof of delivery.</li>
<li>Check the beneficiary details (name, account or wallet); a payment to wrong details may not be recoverable.</li>
</ul>
