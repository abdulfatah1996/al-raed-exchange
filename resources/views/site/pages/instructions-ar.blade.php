<h2>قبل أن تحوّل</h2>
<ul>
<li>لا تحوّل أي مبلغ قبل أن يصلك عرض السعر وتوافق عليه.</li>
<li>حوّل فقط إلى حساب الاستقبال الذي يصلك من رقمنا الرسمي <span class="num">{{ config('alraed.whatsapp_display') }}</span>.</li>
<li>تغيّر حسابات الاستقبال أحيانًا؛ أي تغيير يُعلن في صفحة الإعلانات. إن شككت فاسألنا قبل التحويل.</li>
</ul>
<h2>بعد التحويل</h2>
<ul>
<li>أرسل لنا الإيصال ورقم المعاملة (TXID أو مرجع البنك) مع الرقم المرجعي لطلبك.</li>
<li>صورة الإيصال لا تكفي وحدها: لا نعتمد الحوالة قبل التحقق من وصول المبلغ فعليًا إلى حسابنا.</li>
<li>لكل وصل رقم معاملة واحد؛ لا يمكن استخدام نفس الإيصال أو رقم المعاملة لطلبين.</li>
</ul>
<h2>عند التسليم</h2>
<ul>
<li>نسلّم وفق الطريقة والسعر الذي وافقت عليه، ونحتفظ بإثبات التسليم.</li>
<li>تأكد من صحة بيانات المستفيد (الاسم ورقم الحساب أو المحفظة)؛ التحويل لبيانات خاطئة قد لا يمكن استرداده.</li>
</ul>
