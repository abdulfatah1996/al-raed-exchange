<h2>الطلب والسعر</h2>
<p>إرسال الطلب من الموقع لا يُلزم أي طرف. يصبح السعر ملزمًا فقط بعد إرسال عرضنا وموافقتك عليه، ويبقى السعر المتفق عليه ثابتًا لتلك الحوالة.</p>
<h2>الاعتماد والتسليم</h2>
<p>لا تُعتمد أي حوالة قبل التحقق المستقل من وصول المبلغ. يحق لنا رفض أو تعليق أي معاملة لا تستوفي التحقق أو تثير شبهة.</p>
<h2>مسؤولية البيانات</h2>
<p>أنت مسؤول عن صحة بيانات المستفيد التي ترسلها. لا نتحمل نتائج التحويل إلى بيانات خاطئة قدمتها.</p>
<h2>التوفر</h2>
<p>الخدمات والحسابات والدول متاحة حسب التوفر والسيولة، وقد تتغير دون إشعار مسبق، وتُعلن التغييرات في صفحة الإعلانات.</p>
