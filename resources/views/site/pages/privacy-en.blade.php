<h2>What we collect</h2>
<p>Your name, phone number and the transfer details you send, receipt attachments and delivery proofs, and verification data where applicable rules require it.</p>
<h2>Why we use it</h2>
<ul><li>To carry out your request and contact you about it.</li><li>To verify transfers and prevent fraud and duplicates.</li><li>To keep transaction records as legal and regulatory requirements demand.</li></ul>
<h2>How we protect it</h2>
<p>Sensitive data is stored encrypted, attachments are kept in private storage, and only authorised staff can access them.</p>
<h2>Sharing</h2>
<p>We do not sell your data. We share only what is needed with banks or transfer providers to complete your request, or where the law requires it.</p>
<h2>Your rights</h2>
<p>You can ask to see or correct your data via WhatsApp, subject to records we must keep.</p>
