<h2>البيانات التي نجمعها</h2>
<p>الاسم ورقم الهاتف وتفاصيل الحوالة التي ترسلها في الطلب، ومرفقات الإيصالات وإثباتات التسليم، وما يلزم من بيانات التحقق حسب الضوابط المطبقة.</p>
<h2>لماذا نستخدمها</h2>
<ul><li>لتنفيذ طلبك والتواصل معك بشأنه.</li><li>للتحقق من الحوالات ومنع الاحتيال والتكرار.</li><li>للاحتفاظ بسجل المعاملات كما تقتضي المتطلبات القانونية والتنظيمية.</li></ul>
<h2>كيف نحميها</h2>
<p>تُخزَّن البيانات الحساسة مشفّرة، والمرفقات في مساحة خاصة غير متاحة للعامة، ولا يطّلع عليها إلا الموظفون المصرّح لهم.</p>
<h2>المشاركة</h2>
<p>لا نبيع بياناتك. قد نشارك ما يلزم فقط مع البنوك أو مزودي التحويل لتنفيذ طلبك، أو عند وجود التزام قانوني.</p>
<h2>حقوقك</h2>
<p>يمكنك طلب الاطلاع على بياناتك أو تصحيحها عبر واتساب، مع مراعاة ما يجب الاحتفاظ به من سجلات.</p>
